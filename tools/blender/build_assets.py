def team_material(idx):
    name = "PreviewTeam%d" % idx
    m = bpy.data.materials.get(name)
    if m:
        return m
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    b = m.node_tree.nodes["Principled BSDF"]
    b.inputs["Base Color"].default_value = (*lin3(PREVIEW_TEAM_COLORS[idx]), 1)
    b.inputs["Roughness"].default_value = 0.7
    return m


def apply_team(objs, idx):
    tm = team_material(idx)
    for ob in objs:
        if ob.type != "MESH":
            continue
        for slot in ob.material_slots:
            if slot.material and slot.material.name.startswith("TeamColor"):
                slot.material = tm


def make_camera(elev, azim, ortho_scale=10.0):
    cd = bpy.data.cameras.new("Cam")
    cd.type = "ORTHO"
    cd.ortho_scale = ortho_scale
    cd.clip_start = 0.1
    cd.clip_end = 1000
    cam = bpy.data.objects.new("Cam", cd)
    bpy.context.scene.collection.objects.link(cam)
    e, a = math.radians(elev), math.radians(azim)
    back = Vector((math.cos(e) * math.sin(a), math.cos(e) * math.cos(a), math.sin(e)))
    cam.rotation_euler = (-back).to_track_quat("-Z", "Y").to_euler()
    bpy.context.scene.camera = cam
    return cam, back


def frame_objects(cam, back, objs, margin=1.12, target=None):
    pts = []
    for ob in objs:
        if ob.type == "MESH":
            pts += [ob.matrix_world @ Vector(c) for c in ob.bound_box]
    center = sum(pts, Vector()) / len(pts) if target is None else Vector(target)
    cam.location = center + back * 80
    bpy.context.view_layer.update()
    inv = cam.matrix_world.inverted()
    loc = [inv @ p for p in pts]
    xs = [p.x for p in loc]
    ys = [p.y for p in loc]
    cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    rot = cam.matrix_world.to_3x3()
    cam.location = cam.location + rot @ Vector((cx, cy, 0))
    cam.data.ortho_scale = max(max(xs) - min(xs), max(ys) - min(ys)) * margin
    bpy.context.view_layer.update()


def add_label(cam, text, size_frac=0.055):
    s = cam.data.ortho_scale
    cu = bpy.data.curves.new("Label", "FONT")
    cu.body = text
    cu.size = s * size_frac
    ob = bpy.data.objects.new("Label", cu)
    bpy.context.scene.collection.objects.link(ob)
    ob.parent = cam
    lines = text.count("\n")
    ob.location = (-s * 0.47, -s * 0.47 + cu.size * 1.15 * lines, -2.0)
    ob.visible_shadow = False
    m = bpy.data.materials.new("LabelMat")
    m.use_nodes = True
    nt = m.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs[0].default_value = (0.02, 0.02, 0.02, 1)
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    nt.links.new(em.outputs[0], out.inputs[0])
    cu.materials.append(m)
    return ob


def render_to(path):
    bpy.context.scene.render.filepath = path
    bpy.ops.render.render(write_still=True)


def load_pixels(path):
    import numpy as np
    img = bpy.data.images.load(path)
    w, h = img.size
    px = np.empty(w * h * 4, dtype=np.float32)
    img.pixels.foreach_get(px)
    bpy.data.images.remove(img)
    return px.reshape(h, w, 4)


def save_pixels(arr, path):
    h, w, _ = arr.shape
    img = bpy.data.images.new("Sheet", w, h, alpha=False)
    img.pixels.foreach_set(arr.ravel())
    img.filepath_raw = path
    img.file_format = "PNG"
    img.save()
    bpy.data.images.remove(img)


def render_sheet(category, entries, samples, tile=360, cols=5, info=None):
    import numpy as np
    tmp = tempfile.mkdtemp(prefix="ironbound_tiles_")
    tiles = []
    for name in entries:
        path = glb_path(category, name)
        if not os.path.exists(path):
            continue
        reset_scene()
        setup_render(samples, tile, tile)
        add_preview_ground()
        add_sun()
        objs = import_glb(path)
        apply_team(objs, 0)
        cam, back = make_camera(33.0, 35.0)
        frame_objects(cam, back, objs)
        label = name
        if info and name in info:
            label += "\n%d tris  %.1fm" % (info[name]["tris"],
                                          info[name]["hi"].z - info[name]["lo"].z)
        add_label(cam, label)
        out = os.path.join(tmp, name + ".png")
        render_to(out)
        tiles.append(out)
    if not tiles:
        return None
    rows = (len(tiles) + cols - 1) // cols
    sheet = np.ones((rows * tile, cols * tile, 4), dtype=np.float32)
    sheet[..., :3] = 0.25
    for i, t in enumerate(tiles):
        px = load_pixels(t)
        r, c = divmod(i, cols)
        y0 = (rows - 1 - r) * tile
        sheet[y0 + 2:y0 + tile - 2, c * tile + 2:(c + 1) * tile - 2] = \
            px[2:tile - 2, 2:tile - 2]
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    out = os.path.join(PREVIEW_DIR, category + ".png")
    save_pixels(sheet, out)
    shutil.rmtree(tmp, ignore_errors=True)
    return out


def place_glb(category, name, x, y, rotz=0.0, team=0, z=0.0, scale=1.0):
    path = glb_path(category, name)
    if not os.path.exists(path):
        return []
    objs = import_glb(path)
    apply_team(objs, team)
    root = bpy.data.objects.new("Place_" + name, None)
    bpy.context.scene.collection.objects.link(root)
    root.location = (x, y, z)
    root.rotation_euler = (0, 0, math.radians(rotz))
    root.scale = (scale, scale, scale)
    for ob in objs:
        if ob.parent is None:
            ob.parent = root
    return objs


