def selected_entries(opts):
    out = []
    for cat, name, fn, kw in REGISTRY:
        if opts["category"] and cat != opts["category"]:
            continue
        if opts["only"] and not any(o in name for o in opts["only"]):
            continue
        out.append((cat, name, fn, kw))
    return out


def main():
    opts = parse_args()
    entries = selected_entries(opts)
    results = []
    if opts["build"]:
        for cat, name, fn, kw in entries:
            print("building %s/%s" % (cat, name))
            results.append(build_model(cat, name, fn, kw))
        print_table(results)
    if opts["scene_only"]:
        print("preview:", render_scene_preview(opts["samples"]))
        print("preview:", render_scene_preview(opts["samples"], size=30.0, name="scene_far"))
        return
    if opts["preview"]:
        info = {r["name"]: r for r in results}
        for cat in CATEGORIES:
            if not any(c == cat for c, _, _, _ in entries):
                continue
            # always render the whole category so the sheet stays complete
            names = [n for c, n, _, _ in REGISTRY if c == cat]
            out = render_sheet(cat, names, opts["samples"], info=info)
            print("preview:", out)
        if not opts["only"] and not opts["category"]:
            print("preview:", render_scene_preview(opts["samples"]))
            print("preview:", render_scene_preview(opts["samples"], size=30.0,
                                                   name="scene_far"))


if __name__ == "__main__":
    main()
