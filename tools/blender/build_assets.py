@register_many("env", [("palm_a", {"seed": 1}), ("palm_b", {"seed": 2})])
def palm(M, seed):
    r = rng_for(seed)
    P = M.main
    H = 2.6 if seed == 1 else 2.95
    bend = 0.35 if seed == 1 else -0.25
    segs = 9
    pts, radii = [], []

    def curve(t):
        return Vector((bend * t * t, 0.15 * bend * t, H * t))
    for k in range(segs):
        t0, t1 = k / segs, (k + 1) / segs
        rr = 0.15 - 0.05 * t0
        pts += [curve(t0), curve(t1 - 0.012)]
        radii += [rr, rr * 1.22]
    pts.append(curve(1.0))
    radii.append(0.1)
    P.sweep(pts, radii, m=lambda c, n: "PalmTrunk" if n.z < 0.2 else "PalmTrunkDark",
            n=6, twist=0)
    P.cyl(0.22, 0.14, m="PalmTrunkDark", n=6, r2=0.15)
    top = curve(1.0)
    P.ico(0.16, loc=top + Vector((0, 0, 0.04)), scale=(1, 1, 0.8), m="PalmTrunkDark",
          subdiv=1)
    nf = 9
    for i in range(nf):
        a = 2 * math.pi * i / nf + r.uniform(-0.15, 0.15)
        d = Vector((math.cos(a), math.sin(a), 0))
        side = Vector((-d.y, d.x, 0))
        L = r.uniform(1.25, 1.55)
        rise = r.uniform(0.25, 0.4)
        droop = r.uniform(0.75, 1.0)
        left, mid, right = [], [], []
        steps = 6
        for s in range(steps + 1):
            u = s / steps
            c = top + d * (L * u) + Vector((0, 0, rise * math.sin(math.pi * u * 0.9)
                                            - droop * u * u))
            w = 0.26 * math.sin(math.pi * min(u * 1.1, 1.0)) ** 0.7 + 0.015
            fold = Vector((0, 0, -w * 0.35))
            left.append(c + side * w + fold)
            mid.append(c)
            right.append(c - side * w + fold)
        P.strip([left, mid], m="PalmFrond")
        P.strip([mid, right], m="PalmFrond")
    for i in range(3):  # dry hanging fronds
        a = 2 * math.pi * (i + 0.5) / 3 + r.uniform(-0.3, 0.3)
        d = Vector((math.cos(a), math.sin(a), 0))
        side = Vector((-d.y, d.x, 0))
        base = top + Vector((0, 0, -0.12))
        tip = base + d * 0.35 + Vector((0, 0, -0.85))
        mid = base.lerp(tip, 0.5) + d * 0.12
        rows = [[base + side * 0.04, mid + side * 0.12, tip + side * 0.02],
                [base - side * 0.04, mid - side * 0.12, tip - side * 0.02]]
        P.strip(rows, m="PalmFrondDry")
    for i in range(2):
        a = math.radians(r.uniform(0, 360))
        P.ico(0.12, loc=top + Vector((math.cos(a) * 0.18, math.sin(a) * 0.18, -0.22)),
              scale=(1, 1, 1.4), m="Dates", subdiv=1)


