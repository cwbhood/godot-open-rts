@register_many("env", [("palm_a", {"seed": 1}), ("palm_b", {"seed": 2})])
def palm(M, seed):
    r = rng_for(seed)
    P = M.main
    H = 2.6 if seed == 1 else 2.95
    bend = 0.35 if seed == 1 else -0.25
    segs = 9
    pts, radii = [], []

    def curve(t):
        return Vector((bend * t * t, 0.15 * bend * t, H * t))
    for k in range(segs):
        t0, t1 = k / segs, (k + 1) / segs
        rr = 0.15 - 0.05 * t0
        pts += [curve(t0), curve(t1 - 0.012)]
        radii += [rr, rr * 1.22]
    pts.append(curve(1.0))
    radii.append(0.1)
    P.sweep(pts, radii, m=lambda c, n: "PalmTrunk" if n.z < 0.2 else "PalmTrunkDark",
            n=6, twist=0)
    P.cyl(0.22, 0.14, m="PalmTrunkDark", n=6, r2=0.15)
    top = curve(1.0)
    P.ico(0.16, loc=top + Vector((0, 0, 0.04)), scale=(1, 1, 0.8), m="PalmTrunkDark",
          subdiv=1)
    nf = 9
    for i in range(nf):
        a = 2 * math.pi * i / nf + r.uniform(-0.15, 0.15)
        d = Vector((math.cos(a), math.sin(a), 0))
