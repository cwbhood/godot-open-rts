def rng_for(seed):
    return random.Random(seed * 9973 + 17)


def by_normal(top, side, bottom=None, thr=0.6):
    """Material function: pick by face normal (z up)."""
    bottom = side if bottom is None else bottom

    def fn(c, n):
        if n.z > thr:
            return top
        if n.z < -thr:
            return bottom
        return side
    return fn


def ground_patch(P, radius, m, seed, h=0.04, n=14, irregular=0.18, inner=0.82,
                 loc=(0, 0, 0), scale=(1, 1)):
    """Low irregular blob on the ground (bevelled disc)."""
    r = rng_for(seed)
    jit = [1.0 + r.uniform(-irregular, irregular) for _ in range(n)]
    outer = []
    top = []
    for i in range(n):
        a = 2 * math.pi * i / n
        c, s = math.cos(a) * scale[0], math.sin(a) * scale[1]
        outer.append((loc[0] + c * radius * jit[i], loc[1] + s * radius * jit[i], loc[2]))
        top.append((loc[0] + c * radius * jit[i] * inner,
                    loc[1] + s * radius * jit[i] * inner, loc[2] + h))
    P.add(g_rings([outer, top], cap_start=False, cap_end=True), m)


def rock(P, r, loc, scale=(1, 1, 1), m="Sandstone", seed=0, subdiv=2, rough=0.35,
         freq=1.3, rot=(0, 0, 0)):
    P.ico(r, loc, scale, m, subdiv=subdiv, rough=rough, freq=freq, seed=seed, rot=rot)


def wheel(P, x, y, r, w, z=None, n=8, tire="Rubber", hub="Gunmetal"):
    """Wheel with axis along X centred at (x, y, z)."""
    z = r if z is None else z
    side = 1 if x >= 0 else -1
    P.cyl(r, w, loc=(x, y, z), rot=(0, 90, 0), m=tire, n=n, base=False)
    P.cyl(r * 0.55, 0.03, loc=(x + side * w / 2, y, z), rot=(0, 90, 0), m=hub, n=6,
          base=False)


def track_unit(P, x, length, width, height, m="Track", wheels=4, wheel_m="Gunmetal",
               fender=None, fender_m="SandPaint"):
    """One tank track centred at x, running along Y."""
    L, h = length / 2, height
    b = height * 0.45
    prof = [(-L + b, 0.0), (L - b, 0.0), (L, h * 0.55), (L - b * 0.35, h),
            (-L + b * 0.35, h), (-L, h * 0.55)]
    P.extrude_x(prof, x - width / 2, x + width / 2, m=m)
    side = 1 if x >= 0 else -1
    wr = h * 0.33
    for i in range(wheels):
        y = -L + b + (2 * L - 2 * b) * i / max(wheels - 1, 1)
        P.cyl(wr, 0.012, loc=(x + side * width / 2, y, h * 0.42), rot=(0, 90 * side, 0),
              m=wheel_m, n=6, base=False)
    if fender:
        P.box((width * 1.1, length * 0.98, fender), loc=(x, 0, h + fender / 2), m=fender_m)


