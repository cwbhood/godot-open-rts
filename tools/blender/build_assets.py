def team_material(idx):
    name = "PreviewTeam%d" % idx
    m = bpy.data.materials.get(name)
    if m:
        return m
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    b = m.node_tree.nodes["Principled BSDF"]
    b.inputs["Base Color"].default_value = (*lin3(PREVIEW_TEAM_COLORS[idx]), 1)
