def parse_args():
    argv = sys.argv
    argv = argv[argv.index("--") + 1:] if "--" in argv else argv[1:]
    opts = {"only": None, "category": None, "preview": True,
            "build": True, "samples": 16, "scene_only": False}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--only":
            opts["only"] = [s for s in argv[i + 1].split(",") if s]
            i += 1
        elif a == "--category":
            opts["category"] = argv[i + 1]
            i += 1
        elif a == "--no-preview":
            opts["preview"] = False
        elif a == "--preview-only":
            opts["build"] = False
        elif a == "--scene-only":
            opts["build"] = False
            opts["scene_only"] = True
        elif a == "--samples":
            opts["samples"] = int(argv[i + 1])
            i += 1
        i += 1
    return opts


