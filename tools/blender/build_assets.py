def add_sun(elev=48.0, azim=-140.0, energy=4.2):
    ld = bpy.data.lights.new("Sun", "SUN")
    ld.energy = energy
    ld.color = (1.0, 0.90, 0.74)
    ld.angle = math.radians(2.5)
    ob = bpy.data.objects.new("Sun", ld)
    bpy.context.scene.collection.objects.link(ob)
    # direction the light travels (from sun toward ground)
    e, a = math.radians(elev), math.radians(azim)
    toward = -Vector((math.cos(e) * math.sin(a), math.cos(e) * math.cos(a), math.sin(e)))
    ob.rotation_euler = toward.to_track_quat("-Z", "Y").to_euler()
    return ob


