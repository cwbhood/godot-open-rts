def build_model(category, name, fn, kw):
    reset_scene()
    M = Model(name, category)
    fn(M, **kw)
    tris = M.tris()
    objs = M.finalize(recenter=category in RECENTER_CATEGORIES)
    bpy.context.view_layer.update()
    finish_objects(objs, category)
    tris = sum(len(p.vertices) - 2 for ob in objs.values() for p in ob.data.polygons)
    vs = []
    for ob in objs.values():
        mw = ob.matrix_world
        vs += [mw @ v.co for v in ob.data.vertices]
    lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
    hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
    base = [v for v in vs if v.z < 0.25] or vs
    foot = Vector(((min(v.x for v in base) + max(v.x for v in base)) / 2,
                   (min(v.y for v in base) + max(v.y for v in base)) / 2, 0))
    if "TeamColor" in PALETTE and category in ("units", "buildings"):
        has_team = any(m.name == "TeamColor" for ob in objs.values()
                       for m in ob.data.materials)
        if not has_team:
            print("WARNING: %s has no TeamColor surface" % name)
    export_glb(glb_path(category, name))
    return {"category": category, "name": name, "tris": tris, "lo": lo, "hi": hi,
            "foot": foot,
            "objects": sorted(objs.keys())}


def print_table(results):
    print()
    hdr = "%-10s %-24s %6s  %-17s %-12s %-6s %s" % (
        "category", "model", "tris", "size x*y*z (m)", "foot ctr", "budget", "sub-objects")
    print(hdr)
    print("-" * len(hdr))
    for r in results:
        lo, hi = r["lo"], r["hi"]
        size = "%.2f*%.2f*%.2f" % (hi.x - lo.x, hi.y - lo.y, hi.z - lo.z)
        bmin, bmax = TRI_BUDGET[r["category"]]
        ok = "ok" if bmin <= r["tris"] <= bmax else "OUT"
        extra = [o for o in r["objects"] if o != r["name"]]
        ctr = "%+.2f,%+.2f" % (r["foot"].x, r["foot"].y)
        print("%-10s %-24s %6d  %-17s %-12s %-6s %s" % (r["category"], r["name"], r["tris"],
                                                       size, ctr, ok, ",".join(extra)))
    print()


