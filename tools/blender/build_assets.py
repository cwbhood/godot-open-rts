def render_scene_preview(samples, size=15.0, name="scene", w=1600, h=900):
    """True-scale diorama through the in-game camera (orthographic, 30 deg down)."""
    reset_scene()
    setup_render(samples, w, h)
    add_preview_ground(size=400)
    add_sun()
    for cat, nm, x, y, rz, team in SCENE_LAYOUT:
        objs = place_glb(cat, nm, x, y, rz, team)
        for ob in objs:
            if nm.startswith("helicopter") and ob.parent and ob.parent.name.startswith("Place"):
                ob.parent.location.z = 3.0
    cam, back = make_camera(30.0, 180.0)
    cam.data.ortho_scale = size * w / h
    cam.location = Vector((0, -1.0, 0)) + back * 80
    out = os.path.join(PREVIEW_DIR, name + ".png")
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    render_to(out)
    return out


