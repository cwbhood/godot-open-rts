def V(*a):
    if len(a) == 1:
        return Vector(a[0])
    return Vector(a)


def xform(loc=(0, 0, 0), rot=(0, 0, 0), scale=(1, 1, 1)):
    """Matrix from location, XYZ euler rotation in degrees and scale."""
    if isinstance(scale, (int, float)):
        scale = (scale, scale, scale)
    r = Euler([math.radians(a) for a in rot], "XYZ").to_matrix().to_4x4()
    s = Matrix.Diagonal((scale[0], scale[1], scale[2], 1.0))
    return Matrix.Translation(Vector(loc)) @ r @ s


def g_rings(rings, cap_start=True, cap_end=True, loop=True):
    """Skin consecutive rings of points. A one-point ring becomes an apex."""
    bm = bmesh.new()
    vr = [[bm.verts.new(Vector(p)) for p in r] for r in rings]
    for a, b in zip(vr, vr[1:]):
        if len(a) == 1 and len(b) == 1:
            continue
        if len(a) == 1 or len(b) == 1:
            ring, apex, flip = (b, a[0], False) if len(a) == 1 else (a, b[0], True)
            cnt = len(ring) if loop else len(ring) - 1
            for j in range(cnt):
                tri = (apex, ring[(j + 1) % len(ring)], ring[j]) if not flip else \
                    (ring[j], ring[(j + 1) % len(ring)], apex)
                try:
                    bm.faces.new(tri)
                except ValueError:
                    pass
            continue
        cnt = len(a) if loop else len(a) - 1
        for j in range(cnt):
            j2 = (j + 1) % len(a)
            try:
                bm.faces.new((a[j], a[j2], b[j2], b[j]))
            except ValueError:
                pass
    if cap_start and len(vr[0]) > 2:
        try:
            bm.faces.new(list(reversed(vr[0])))
        except ValueError:
            pass
    if cap_end and len(vr[-1]) > 2:
        try:
            bm.faces.new(vr[-1])
        except ValueError:
            pass
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    if cap_start and cap_end and loop:
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    return bm


def circle_pts(r, n, z=0.0, phase=0.0, rx=None, ry=None):
    rx = r if rx is None else rx
    ry = r if ry is None else ry
    return [(math.cos(phase + 2 * math.pi * i / n) * rx,
             math.sin(phase + 2 * math.pi * i / n) * ry, z) for i in range(n)]


def g_prism(poly, h, top_scale=1.0, top_shift=(0, 0), base=True):
    """Extrude an XY polygon (CCW) along +Z. top_scale may be a float or (sx, sy)."""
    if isinstance(top_scale, (int, float)):
        top_scale = (top_scale, top_scale)
    z0 = 0.0 if base else -h / 2
    bot = [(x, y, z0) for x, y in poly]
    top = [(x * top_scale[0] + top_shift[0], y * top_scale[1] + top_shift[1], z0 + h)
           for x, y in poly]
    return g_rings([bot, top])


def g_box(sx, sy, sz, base=False, taper=1.0, top_shift=(0, 0)):
    hx, hy = sx / 2, sy / 2
    bm = g_prism([(-hx, -hy), (hx, -hy), (hx, hy), (-hx, hy)], sz,
                 top_scale=taper, top_shift=top_shift, base=True)
    if not base:
        bmesh.ops.translate(bm, vec=(0, 0, -sz / 2), verts=bm.verts)
    return bm


def g_cyl(r, h, n=8, r2=None, base=True, phase=None, caps=True):
    r2 = r if r2 is None else r2
    phase = math.pi / n if phase is None else phase
    z0 = 0.0 if base else -h / 2
    bot = circle_pts(r, n, z0, phase)
    top = circle_pts(r2, n, z0 + h, phase) if r2 > 1e-6 else [(0, 0, z0 + h)]
    return g_rings([bot, top], cap_start=caps, cap_end=caps)


def g_lathe(profile, n=8, phase=None, caps=True):
    """Revolve [(radius, z), ...] around Z. Radius 0 gives a pole."""
    phase = math.pi / n if phase is None else phase
    rings = []
    for r, z in profile:
        rings.append([(0, 0, z)] if r < 1e-6 else circle_pts(r, n, z, phase))
    return g_rings(rings, cap_start=caps, cap_end=caps)


def g_ico(r=1.0, subdiv=2):
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=subdiv, radius=r)
    return bm


def sweep_rings(points, radii, n=6, profile=None, twist=0.0, phase=0.0):
    """Rings along a polyline. radii: float or (rx, ry) per point."""
    pts = [Vector(p) for p in points]
    if profile is None:
        profile = [(math.cos(phase + 2 * math.pi * i / n),
                    math.sin(phase + 2 * math.pi * i / n)) for i in range(n)]
    tangents = []
    for i in range(len(pts)):
        a = pts[max(i - 1, 0)]
        b = pts[min(i + 1, len(pts) - 1)]
        t = (b - a)
        tangents.append(t.normalized() if t.length > 1e-9 else Vector((0, 0, 1)))
    t0 = tangents[0]
    ref = Vector((1, 0, 0)) if abs(t0.z) > 0.8 else Vector((0, 0, 1))
    nrm = (ref - t0 * ref.dot(t0)).normalized()
    rings = []
    for i, (p, t) in enumerate(zip(pts, tangents)):
        nrm = (nrm - t * nrm.dot(t))
        nrm = nrm.normalized() if nrm.length > 1e-9 else t.orthogonal().normalized()
        bi = t.cross(nrm)
        rad = radii[i] if isinstance(radii, (list, tuple)) else radii
        rx, ry = (rad, rad) if isinstance(rad, (int, float)) else rad
        ang = math.radians(twist) * i
        ca, sa = math.cos(ang), math.sin(ang)
        ring = []
        for (u, v) in profile:
            u2, v2 = u * ca - v * sa, u * sa + v * ca
            ring.append(p + nrm * (u2 * rx) + bi * (v2 * ry))
        rings.append(ring)
    return rings


