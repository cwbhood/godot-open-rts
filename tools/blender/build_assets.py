def layered_column(P, base, layers, seed, n=7):
    """Stack of irregular frustums with ledges, alternating sandstone tones."""
    r = rng_for(seed)
    z = base.z
    mats = ["Sandstone", "SandstoneDark", "SandstoneLight", "Sandstone"]
    for i, (rad, h) in enumerate(layers):
        jit = [1 + r.uniform(-0.18, 0.18) for _ in range(n)]
        off = Vector((r.uniform(-0.06, 0.06), r.uniform(-0.06, 0.06), 0))
        phase = r.uniform(0, math.pi)
        bot = [(base.x + off.x + x * j, base.y + off.y + y * j, z)
               for (x, y, _), j in zip(circle_pts(rad, n, 0, phase), jit)]
        top = [(base.x + off.x + x * j * 0.9, base.y + off.y + y * j * 0.9, z + h)
               for (x, y, _), j in zip(circle_pts(rad, n, 0, phase), jit)]
        cap = [(x * 0.97 + (base.x + off.x) * 0.03, y * 0.97 + (base.y + off.y) * 0.03,
                z + h + 0.03) for x, y, _ in top]
        top_m = "SandstoneLight" if i == len(layers) - 1 else mats[(i + 1) % 4]
        P.add(g_rings([bot, top], True, False), mats[i % 4])
        P.add(g_rings([top, cap], False, True), top_m)
        z += h


