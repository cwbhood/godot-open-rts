"""Ironbound procedural low-poly asset builder.

Builds every Ironbound model from scratch with bmesh, exports one .glb per
model into assets/models/ironbound/<category>/ and (optionally) renders a
contact-sheet preview per category into tools/blender/previews/.

Run (from the repository root):
    python3.11 tools/blender/build_assets.py            # bpy as a Python module
    blender -b -P tools/blender/build_assets.py         # desktop Blender
Options (after "--" when running through the blender binary):
    --only NAME[,NAME...]   build only models whose name contains one of these
    --category CAT          build only one category (env, deposits, units, buildings)
    --no-preview            skip the preview renders
    --preview-only          skip building, only render previews from existing GLBs
    --samples N             Cycles samples for previews (default 16)

Conventions (the game code depends on them):
    * 1 Blender unit = 1 m. Origin at the bottom centre, model sits on z = 0.
    * Front of vehicles/buildings faces Blender +Y (Godot -Z after export).
    * Flat shaded, a handful of named Principled materials, no textures.
    * Team-coloured surfaces use the material named exactly "TeamColor".
    * Animated sub-parts are separate child objects with their origin at the
      pivot: "Turret", "Beam", "Rotor", "Rotor2", "RotorTail".
All geometry is generated by this script; the output is our own work (CC0).
"""

