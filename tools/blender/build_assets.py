# Built at in-game size: the footprint fills the structure's radius (command
# centre 4 m, factories 3.2 m, power plant 2.3 m, extractors 1.9 m, turrets 1.3 m,
# city buildings 2 m). Military structures stand on a dark concrete pad so the
# footprint reads against the sand; roofs are dark with team-coloured trims and
# panels; walls are mid-grey concrete, brick or steel, never sand-coloured.

def lattice(P, base_half, top_half, z0, z1, levels, m="Steel", w=0.05, leg_w=None,
            diag=True):
    """Square lattice tower centred on the current frame origin."""
    corners = [(-1, -1), (1, -1), (1, 1), (-1, 1)]

    def pt(c, t):
        h = base_half + (top_half - base_half) * t
        return Vector((c[0] * h, c[1] * h, z0 + (z1 - z0) * t))
    for c in corners:
        P.beam(pt(c, 0), pt(c, 1), leg_w or w * 1.4, m)
    for lv in range(levels):
        t0, t1 = lv / levels, (lv + 1) / levels
        for k in range(4):
            a, b = corners[k], corners[(k + 1) % 4]
            P.beam(pt(a, t1), pt(b, t1), w, m, caps=False)
            if diag:
                if (lv + k) % 2 == 0:
                    P.beam(pt(a, t0), pt(b, t1), w * 0.8, m, caps=False)
                else:
                    P.beam(pt(b, t0), pt(a, t1), w * 0.8, m, caps=False)


def sandbag_ring(P, r, count, rows=2, z0=0.0, gap=None, bag_h=0.08):
    for row in range(rows):
        for i in range(count):
            a = 2 * math.pi * (i + 0.5 * (row % 2)) / count
            if gap and abs(((math.degrees(a) - gap[0] + 180) % 360) - 180) < gap[1]:
                continue
            length = 2 * math.pi * r / count * 1.08
            P.box((length, 0.15, bag_h), loc=(math.cos(a) * r, math.sin(a) * r,
                                              z0 + row * bag_h * 0.92),
                  rot=(0, 0, math.degrees(a) + 90), base=True, taper=(0.9, 0.7),
                  m="Sandbag")


