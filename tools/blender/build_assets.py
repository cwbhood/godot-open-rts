def add_sun(elev=48.0, azim=-140.0, energy=4.2):
    ld = bpy.data.lights.new("Sun", "SUN")
    ld.energy = energy
    ld.color = (1.0, 0.90, 0.74)
    ld.angle = math.radians(2.5)
    ob = bpy.data.objects.new("Sun", ld)
