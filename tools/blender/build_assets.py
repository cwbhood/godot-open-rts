# emissive strength per material (glTF emissive, picked up by Godot's glow)
EMISSIVE = {"Lamp": 1.2, "TailLight": 1.5, "Glow": 2.5, "WindowLit": 0.9}


def get_mat(name):
    m = bpy.data.materials.get(name)
    if m is not None:
        return m
    srgb, rough, metal, double = PALETTE[name]
    lin = tuple(srgb_to_linear(c) for c in srgb)
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*lin, 1.0)
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    m.diffuse_color = (*lin, 1.0)
    m.roughness = rough
    m.metallic = metal
    m.use_backface_culling = not double
    if name in EMISSIVE:
        bsdf.inputs["Emission Color"].default_value = (*lin, 1.0)
        bsdf.inputs["Emission Strength"].default_value = EMISSIVE[name]
    return m


