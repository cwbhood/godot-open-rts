class Part:
    """Accumulates geometry for one exported object, in model space."""

    def __init__(self, name, origin=(0, 0, 0), parent=None):
        self.name = name
        self.origin = Vector(origin)
        self.parent = parent
        self.bm = bmesh.new()
        self.mats = []
        self.stack = [Matrix.Identity(4)]

    # -- transform stack --
    @contextmanager
    def at(self, loc=(0, 0, 0), rot=(0, 0, 0), scale=(1, 1, 1)):
        self.stack.append(self.stack[-1] @ xform(loc, rot, scale))
        try:
            yield self
        finally:
            self.stack.pop()

    def _mi(self, name):
        if name not in self.mats:
            self.mats.append(name)
        return self.mats.index(name)

    def add(self, pbm, m, local=None):
        M = self.stack[-1] @ (local if local is not None else Matrix.Identity(4))
        bmesh.ops.transform(pbm, matrix=M, verts=pbm.verts)
        if M.determinant() < 0:
            bmesh.ops.reverse_faces(pbm, faces=pbm.faces)
        pbm.normal_update()
        vmap = {v: self.bm.verts.new(v.co) for v in pbm.verts}
        for f in pbm.faces:
            try:
                nf = self.bm.faces.new([vmap[v] for v in f.verts])
            except ValueError:
                continue
            name = m(f.calc_center_median(), f.normal) if callable(m) else m
            nf.material_index = self._mi(name)
            nf.smooth = False
        pbm.free()
        return self

    # -- primitives (all lengths in metres, angles in degrees) --
    def box(self, size, loc=(0, 0, 0), rot=(0, 0, 0), m="Concrete", base=False,
            taper=1.0, top_shift=(0, 0)):
        return self.add(g_box(*size, base=base, taper=taper, top_shift=top_shift), m,
                        xform(loc, rot))

    def cyl(self, r, h, loc=(0, 0, 0), rot=(0, 0, 0), m="Concrete", n=8, r2=None,
            base=True, scale=(1, 1, 1), caps=True, phase=None):
        return self.add(g_cyl(r, h, n, r2, base, phase, caps), m, xform(loc, rot, scale))

    def cone(self, r, h, loc=(0, 0, 0), rot=(0, 0, 0), m="Concrete", n=8, scale=(1, 1, 1)):
        return self.cyl(r, h, loc, rot, m, n, r2=0.0, scale=scale)

    def lathe(self, profile, loc=(0, 0, 0), rot=(0, 0, 0), m="Concrete", n=8,
              scale=(1, 1, 1), caps=True, phase=None):
        return self.add(g_lathe(profile, n, phase, caps), m, xform(loc, rot, scale))

    def prism(self, poly, h, loc=(0, 0, 0), rot=(0, 0, 0), m="Concrete",
              top_scale=1.0, top_shift=(0, 0), base=True, scale=(1, 1, 1)):
        return self.add(g_prism(poly, h, top_scale, top_shift, base), m,
                        xform(loc, rot, scale))

    def extrude_x(self, poly_yz, x0, x1, m="Concrete", loc=(0, 0, 0), rot=(0, 0, 0)):
        """Side profile [(y, z), ...] extruded along X from x0 to x1."""
        a = [(x0, y, z) for y, z in poly_yz]
        b = [(x1, y, z) for y, z in poly_yz]
        return self.add(g_rings([a, b]), m, xform(loc, rot))

    def extrude_y(self, poly_xz, y0, y1, m="Concrete", loc=(0, 0, 0), rot=(0, 0, 0)):
        """Front profile [(x, z), ...] extruded along Y from y0 to y1."""
        a = [(x, y0, z) for x, z in poly_xz]
        b = [(x, y1, z) for x, z in poly_xz]
        return self.add(g_rings([a, b]), m, xform(loc, rot))

    def ico(self, r=1.0, loc=(0, 0, 0), scale=(1, 1, 1), m="Concrete", subdiv=2,
            rough=0.0, freq=1.5, seed=0, rot=(0, 0, 0)):
        bm = g_ico(r, subdiv)
        if rough:
            off = Vector((seed * 7.31, seed * 3.17, seed * 5.53))
            for v in bm.verts:
                d = noise.noise(v.co * freq / max(r, 1e-3) + off)
                v.co *= 1.0 + rough * d
        return self.add(bm, m, xform(loc, rot, scale))

    def sweep(self, points, radii, m="Bark", n=6, profile=None, twist=0.0,
              caps=(True, True), phase=0.0):
        rings = sweep_rings(points, radii, n, profile, twist, phase)
        return self.add(g_rings(rings, caps[0], caps[1]), m)

    def beam(self, p1, p2, w=0.05, m="Steel", h=None, n=4, caps=True):
        """Square (n=4) or round strut between two points."""
        h = w if h is None else h
        return self.sweep([p1, p2], (w / 2 * 1.4142, h / 2 * 1.4142) if n == 4 else w / 2,
                          m=m, n=n, phase=math.pi / 4 if n == 4 else 0.0,
                          caps=(caps, caps))

    def poly(self, points, m="Canvas"):
        bm = bmesh.new()
        bm.faces.new([bm.verts.new(Vector(p)) for p in points])
        return self.add(bm, m)

    def strip(self, rows, m="Canvas"):
        """rows: list of point lists (same length); skinned as an open sheet."""
        return self.add(g_rings(rows, False, False, loop=False), m)

    # -- post processing --
    def clamp_ground(self, z=0.0):
        for v in self.bm.verts:
            if v.co.z < z:
                v.co.z = z

    def tris(self):
        return sum(len(f.verts) - 2 for f in self.bm.faces)


class Model:
    def __init__(self, name, category):
        self.name = name
        self.category = category
        self.parts = [Part(name)]
        self.main = self.parts[0]

    def part(self, name, origin=(0, 0, 0), parent=None):
        p = Part(name, origin, parent or self.main)
        self.parts.append(p)
        return p

    def tris(self):
        return sum(p.tris() for p in self.parts)

    def bounds(self):
        vs = [v.co for p in self.parts for v in p.bm.verts]
        lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
        hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
        return lo, hi

    def finalize(self, recenter=False):
        """Snap to ground (and optionally centre the ground footprint on the origin),
        then create Blender objects with origins at their pivots."""
        lo, _ = self.bounds()
        dz = Vector((0, 0, -lo.z))
        if recenter:
            base = [v.co for p in self.parts for v in p.bm.verts if v.co.z < lo.z + 0.25]
            dz.x = -(min(v.x for v in base) + max(v.x for v in base)) / 2
            dz.y = -(min(v.y for v in base) + max(v.y for v in base)) / 2
        objs = {}
        for p in self.parts:
            bmesh.ops.translate(p.bm, vec=dz, verts=p.bm.verts)
            if p is not self.main:  # the root object always stays at the origin
                p.origin = p.origin + dz
            bmesh.ops.translate(p.bm, vec=-p.origin, verts=p.bm.verts)
            mesh = bpy.data.meshes.new(p.name)
            p.bm.to_mesh(mesh)
            for mn in p.mats:
                mesh.materials.append(get_mat(mn))
            ob = bpy.data.objects.new(p.name, mesh)
            bpy.context.scene.collection.objects.link(ob)
            objs[p.name] = ob
        for p in self.parts:
            ob = objs[p.name]
            if p.parent is not None:
                par = objs[p.parent.name]
                ob.parent = par
                ob.location = p.origin - p.parent.origin
            else:
                ob.location = p.origin
        return objs



# --------------------------------------------------------------------------
# Finishing pass: bevelled edges and baked ambient occlusion
# --------------------------------------------------------------------------
# Units and buildings get a narrow bevel on every hard edge, so edges catch the
# light and silhouettes read at game zoom, and ambient occlusion baked into the
# COLOR_0 vertex colours (Godot multiplies the albedo by it), so crevices, the
# ground contact and the undersides darken. Values are linear multipliers.

FINISH = {
    "units": {"bevel": 0.012, "ao_dist": 0.3, "ao_min": 0.38, "ground_h": 0.22,
              "ground_dark": 0.72},
    "buildings": {"bevel": 0.022, "ao_dist": 0.7, "ao_min": 0.42, "ground_h": 0.5,
                  "ground_dark": 0.75},
}
AO_RAYS = 20


def _hemisphere_dirs(count):
    """Cosine-weighted directions around +Z (deterministic)."""
    dirs = []
    golden = math.pi * (3.0 - math.sqrt(5.0))
    for i in range(count):
        u = (i + 0.5) / count
        r = math.sqrt(u)
        a = golden * i
        dirs.append(Vector((r * math.cos(a), r * math.sin(a), math.sqrt(max(0.0, 1 - u)))))
    return dirs


def _bevel(ob, width):
    mod = ob.modifiers.new("Bevel", "BEVEL")
    mod.width = width
    mod.segments = 1
    mod.limit_method = "ANGLE"
    mod.angle_limit = math.radians(35)
    mod.use_clamp_overlap = True
    mod.miter_outer = "MITER_ARC"


def finish_objects(objs, category):
    cfg = FINISH.get(category)
    if cfg is None:
        return
    for ob in objs.values():
        _bevel(ob, cfg["bevel"])
    bpy.context.view_layer.update()
    dg = bpy.context.evaluated_depsgraph_get()
    for ob in objs.values():
        me = bpy.data.meshes.new_from_object(ob.evaluated_get(dg))
        old = ob.data
        ob.modifiers.clear()
        ob.data = me
        name = old.name
        bpy.data.meshes.remove(old)
        me.name = name
    bpy.context.view_layer.update()
    # occluders: every part in world space plus a ground plane
    verts, polys = [], []
    for ob in objs.values():
        mw = ob.matrix_world
        base = len(verts)
        verts += [mw @ v.co for v in ob.data.vertices]
        polys += [[base + i for i in p.vertices] for p in ob.data.polygons]
    base = len(verts)
    g = 60.0
    verts += [Vector((-g, -g, -0.001)), Vector((g, -g, -0.001)), Vector((g, g, -0.001)),
              Vector((-g, g, -0.001))]
    polys.append([base, base + 1, base + 2, base + 3])
    bvh = BVHTree.FromPolygons(verts, polys)
    dirs = _hemisphere_dirs(AO_RAYS)
    maxd = cfg["ao_dist"]
    for ob in objs.values():
        me = ob.data
        mw = ob.matrix_world
        nm = mw.to_3x3().inverted().transposed()
        attr = me.color_attributes.new("Col", "BYTE_COLOR", "CORNER")
        cache = {}
        for poly in me.polygons:
            n = (nm @ poly.normal).normalized()
            t = n.orthogonal().normalized()
            b = n.cross(t)
            for li in poly.loop_indices:
                vi = me.loops[li].vertex_index
                key = (vi, round(n.x, 2), round(n.y, 2), round(n.z, 2))
                c = cache.get(key)
                if c is None:
                    p = mw @ me.vertices[vi].co
                    # pull the sample point slightly into the face so the rays
                    # do not start exactly on shared edges
                    centre = mw @ poly.center
                    p = p + (centre - p) * 0.02 + n * 0.002
                    occ = 0.0
                    for d in dirs:
                        w = t * d.x + b * d.y + n * d.z
                        hit = bvh.ray_cast(p, w, maxd)
                        if hit[0] is not None:
                            occ += 1.0 - (hit[3] / maxd) ** 1.5
                    ao = 1.0 - occ / len(dirs)
                    ao = cfg["ao_min"] + (1.0 - cfg["ao_min"]) * ao
                    h = min(max(p.z / cfg["ground_h"], 0.0), 1.0)
                    h = h * h * (3 - 2 * h)
                    ao *= cfg["ground_dark"] + (1.0 - cfg["ground_dark"]) * h
                    c = (ao, ao, ao, 1.0)
                    cache[key] = c
                attr.data[li].color = c
        me.color_attributes.active_color = attr
        me.color_attributes.render_color_index = 0

